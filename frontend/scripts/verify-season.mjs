import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.route('**/api/v1/**',route=>{ const path=new URL(route.request().url()).pathname; return route.fulfill({json:path.endsWith('/problem-statements')?{items:[],total:0}:[]}); });
await page.goto('http://127.0.0.1:4173/');
await page.waitForTimeout(1800);
await page.screenshot({path:'.qa/season-home-1440.png'});
await page.locator('#replay').scrollIntoViewIfNeeded();
const cdp=await page.context().newCDPSession(page);
await cdp.send('HeapProfiler.collectGarbage');
const before=await cdp.send('Runtime.getHeapUsage');
await page.evaluate(()=>{window.__flightSamples=[];let previous=performance.now();function sample(now){window.__flightSamples.push(now-previous);previous=now;if(window.__flightSamples.length<360)requestAnimationFrame(sample);}requestAnimationFrame(sample);});
await page.getByRole('button',{name:'Launch flight',exact:true}).click();
await page.waitForTimeout(2700);
await page.locator('#replay').screenshot({path:'.qa/season-flight-1440.png'});
await page.getByRole('button',{name:'Replay flight'}).waitFor();
await page.getByRole('button',{name:'Replay flight'}).click();
await cdp.send('HeapProfiler.collectGarbage');
const after=await cdp.send('Runtime.getHeapUsage');
const samples=await page.evaluate(()=>window.__flightSamples);
const report={context:'Local Chrome, desktop 1440x1000, no CPU throttling; API fixture responses; one flight including screenshot capture. Not a mid-range hardware or field INP measurement.',frames:samples.length,medianFrameMs:[...samples].sort((a,b)=>a-b)[Math.floor(samples.length/2)],framesOver33ms:samples.filter(x=>x>33).length,heapBeforeBytes:before.usedSize,heapAfterReplayBytes:after.usedSize,remainingJetAnimations:await page.locator('.flight-jet').evaluate(el=>el.getAnimations().length)};
await fs.writeFile('.qa/season-motion-report.json',JSON.stringify(report,null,2));
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4173/');await page.waitForTimeout(1800);
await page.screenshot({path:'.qa/season-home-390.png'});
await page.locator('.season-next').scrollIntoViewIfNeeded();
await page.getByRole('button',{name:'Launch flight',exact:true}).click();await page.waitForTimeout(2700);
await page.locator('.season-next').screenshot({path:'.qa/season-flight-390.png'});
console.log(JSON.stringify(report));
await browser.close();
